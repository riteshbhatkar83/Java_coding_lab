public class Rit_JavaUseStaticPrimitive {
   
     public static void main(String[] args) {
        
        int age = 21;     // primitive variable
        double marks = 85.5;

        System.out.println("Age = " + age);
        System.out.println("Marks = " + marks);
    }
}


// 🔸 Output
// Age = 21
// Marks = 85.5

// 👉 ✔ age and marks are primitive variables
// 👉 ✔ Stored in stack memory
// 👉 ✔ Fixed size → static allocation